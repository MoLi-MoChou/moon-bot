// Emits production JavaScript for the host (and shared modules it imports) so the
// plugin can load under node_modules. Node 22 will not strip types for paths under
// node_modules (ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING); Docker and `file:`
// installs therefore need plain .js.
//
//   node scripts/build-host.mjs           writes dist/host and dist/shared
//   node scripts/build-host.mjs --check   exits 1 when dist is missing or stale
//
// Sources stay TypeScript (tsc --noEmit, allowImportingTsExtensions). index.js
// imports the emitted .js modules. Tests that import .ts from src/ still use
// Node's type stripping outside node_modules.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const PLUGIN = dirname(dirname(fileURLToPath(import.meta.url)))
const OUT = join(PLUGIN, 'dist')
const LAYERS = ['host', 'shared', 'engine', 'store', 'web-search']
// Source files at src/ root: emitted to dist/ root, with a generated re-export shim at
// the package root so `main`/`exports` keep naming plain .js files.
const ROOT_ENTRIES = ['index.ts', 'web-search.ts']

function collectTs(dir, out = []) {
  if (!existsSync(dir)) return out
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) collectTs(path, out)
    else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) out.push(path)
  }
  return out
}

/** The generated package-root file that re-exports a dist entry. Banner added with all others. */
function rootShim(rel) {
  const name = rel.replace(/\.ts$/, '')
  return {
    [`../${name}.js`]: `export * from './dist/${name}.js'\n`,
  }
}

/** Rewrite runtime `.ts` import/export specifiers to `.js` (type-only imports are already stripped). */
function rewriteTsSpecifiers(text) {
  return text
    .replace(/(\bfrom\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
    .replace(/(\bimport\s*\(\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
    .replace(/(\bexport\s+\*\s+from\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
}

function fingerprint(dir) {
  if (!existsSync(dir)) return ''
  const hash = createHash('sha256')
  const walk = (base) => {
    for (const name of readdirSync(base).sort()) {
      const path = join(base, name)
      const st = statSync(path)
      if (st.isDirectory()) walk(path)
      else {
        hash.update(relative(dir, path).split(/[\\/]/).join('/'))
        hash.update('\0')
        hash.update(readFileSync(path))
        hash.update('\0')
      }
    }
  }
  walk(dir)
  return hash.digest('hex')
}

export async function emitHost() {
  const entries = [
    ...LAYERS.flatMap(layer => collectTs(join(PLUGIN, 'src', layer))),
    ...ROOT_ENTRIES.map(name => join(PLUGIN, 'src', name)).filter(path => existsSync(path)),
  ]
  if (entries.length === 0) throw new Error('build-host: no .ts sources under src/')

  const result = await build({
    absWorkingDir: PLUGIN,
    entryPoints: entries,
    outdir: OUT,
    outbase: join(PLUGIN, 'src'),
    bundle: false,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    packages: 'external',
    tsconfig: join(PLUGIN, 'tsconfig.json'),
    write: false,
    logLevel: 'silent',
    sourcemap: false,
  })
  if (result.warnings.length > 0) {
    throw new Error(`build-host esbuild warnings:\n${result.warnings.map(w => w.text).join('\n')}`)
  }

  const files = new Map()
  for (const file of result.outputFiles) {
    // esbuild outdir paths; normalize to dist-relative posix keys for stable --check.
    const rel = relative(OUT, file.path).split(/[\\/]/).join('/')
    files.set(rel, rewriteTsSpecifiers(file.text))
  }
  // The package-root shims that keep `main` and `exports` on plain .js files. Their keys
  // sit outside dist/ (../index.js), so the writer and the checker both treat them as
  // paths relative to dist/'s parent when read or written.
  for (const name of ROOT_ENTRIES) {
    if (!files.has(`${name.replace(/\.ts$/, '')}.js`)) continue
    for (const [rel, text] of Object.entries(rootShim(name))) files.set(rel, text)
  }
  // Banner so a reader knows not to edit by hand.
  const banner = '// Generated by `node scripts/build-host.mjs`. Do not edit by hand.\n'
  for (const [rel, text] of files) files.set(rel, banner + text)
  return files
}

function writeEmit(files) {
  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  for (const [rel, text] of files) {
    const path = join(OUT, rel)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
  }
}

function readEmit() {
  const files = new Map()
  if (!existsSync(OUT)) return files
  const walk = (base, prefix = '') => {
    for (const name of readdirSync(base).sort()) {
      const path = join(base, name)
      const rel = prefix ? `${prefix}/${name}` : name
      if (statSync(path).isDirectory()) walk(path, rel)
      else files.set(rel, readFileSync(path, 'utf8'))
    }
  }
  walk(OUT)
  // The package-root shims are part of the emit: read them so --check sees a stale shim.
  for (const name of ROOT_ENTRIES) {
    const base = name.replace(/\.ts$/, '')
    const shim = join(PLUGIN, `${base}.js`)
    if (existsSync(shim) && existsSync(join(OUT, `${base}.js`))) files.set(`../${base}.js`, readFileSync(shim, 'utf8'))
  }
  return files
}

function sameEmit(expected, actual) {
  if (expected.size !== actual.size) return false
  for (const [rel, text] of expected) {
    if (actual.get(rel) !== text) return false
  }
  return true
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await emitHost()
  if (process.argv.includes('--check')) {
    const current = readEmit()
    if (!sameEmit(next, current)) {
      console.error('dist/ is stale or missing: run `node scripts/build-host.mjs` in core and commit the result')
      process.exit(1)
    }
  } else {
    writeEmit(next)
    console.log(`build-host: wrote ${next.size} files under dist/ (${fingerprint(OUT).slice(0, 12)})`)
  }
}
