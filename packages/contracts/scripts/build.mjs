// Emits plain .js under dist/ so Node can load contracts from node_modules
// (no type stripping there). Sources stay TypeScript for typecheck and editors.
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const PKG = dirname(dirname(fileURLToPath(import.meta.url)))
const SRC = join(PKG, 'src')
const OUT = join(PKG, 'dist')

function collectTs(dir, out = []) {
  if (!existsSync(dir)) return out
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) collectTs(path, out)
    else if (entry.name.endsWith('.ts') && !entry.name.endsWith('.d.ts')) out.push(path)
  }
  return out
}

function rewriteTsSpecifiers(text) {
  return text
    .replace(/(\bfrom\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
    .replace(/(\bimport\s*\(\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
    .replace(/(\bexport\s+\*\s+from\s*['"])([^'"]+)\.ts(['"])/g, '$1$2.js$3')
}

function fingerprint(dir) {
  if (!existsSync(dir)) return ''
  const hash = createHash('sha256')
  const walk = (base) => {
    for (const name of readdirSync(base).sort()) {
      const path = join(base, name)
      const st = statSync(path)
      if (st.isDirectory()) walk(path)
      else {
        hash.update(relative(dir, path).split(/[\\/]/).join('/'))
        hash.update('\0')
        hash.update(readFileSync(path))
        hash.update('\0')
      }
    }
  }
  walk(dir)
  return hash.digest('hex')
}

export async function emitContracts() {
  const entries = collectTs(SRC)
  if (entries.length === 0) throw new Error('build-contracts: no .ts sources under src/')
  const result = await build({
    absWorkingDir: PKG,
    entryPoints: entries,
    outdir: OUT,
    outbase: SRC,
    bundle: false,
    format: 'esm',
    platform: 'node',
    target: 'node22',
    packages: 'external',
    tsconfig: join(PKG, 'tsconfig.json'),
    write: false,
    logLevel: 'silent',
    sourcemap: false,
  })
  if (result.warnings.length > 0) {
    throw new Error(`build-contracts esbuild warnings:\n${result.warnings.map(w => w.text).join('\n')}`)
  }
  const files = new Map()
  const banner = '// Generated by `node scripts/build.mjs`. Do not edit by hand.\n'
  for (const file of result.outputFiles) {
    const rel = relative(OUT, file.path).split(/[\\/]/).join('/')
    files.set(rel, banner + rewriteTsSpecifiers(file.text))
  }
  return files
}

function writeEmit(files) {
  rmSync(OUT, { recursive: true, force: true })
  mkdirSync(OUT, { recursive: true })
  for (const [rel, text] of files) {
    const path = join(OUT, rel)
    mkdirSync(dirname(path), { recursive: true })
    writeFileSync(path, text)
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = await emitContracts()
  writeEmit(next)
  console.log(`build-contracts: wrote ${next.size} files under dist/ (${fingerprint(OUT).slice(0, 12)})`)
}
